#!/usr/bin/env node
// Prepares the libraries code layers can import (three, gsap, motion) as plain
// ES modules under editor/public/vendor/. Vite serves public/ in dev and copies
// it into dist/ (and so into the app bundle); the Mac scheme handler and the
// headless host serve it with Access-Control-Allow-Origin: * because code
// frames run in an opaque origin and must fetch modules with CORS.
//
//   vendor/three/three.module.js, three.core.js   (copied)
//   vendor/three/examples/jsm/...                 (copied subset: "three/addons/")
//   vendor/gsap/*.js                              (copied; core + plugins)
//   vendor/motion/motion.js                       (bundled from `motion`, minified)
//
// The output is generated, not committed. It is rebuilt when the pinned
// versions or this script change (stamp file), so `bun run dev|build` stay fast.

import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'vendor');
const NM = join(ROOT, 'node_modules');

/** three/examples/jsm directories that are excluded: physics, WebGPU renderers, exporters, dev tools. */
const THREE_ADDON_EXCLUDE = new Set(['inspector', 'physics', 'transpiler', 'offscreen', 'webxr', 'exporters', 'pipelines', 'renderers']);
/** Wasm decoders that load their binaries over the network (blocked by the code frame's CSP anyway). */
const THREE_ADDON_EXCLUDE_PATHS = ['libs/basis', 'libs/draco'];

async function version(pkg) {
  return JSON.parse(await readFile(join(NM, pkg, 'package.json'), 'utf8')).version;
}

async function main() {
  const versions = { three: await version('three'), gsap: await version('gsap'), motion: await version('motion') };
  const script = await readFile(fileURLToPath(import.meta.url));
  const entry = await readFile(join(ROOT, 'scripts', 'vendor-motion-entry.mjs'));
  const stamp = createHash('sha256').update(JSON.stringify(versions)).update(script).update(entry).digest('hex');
  const stampFile = join(OUT, '.stamp');
  if (existsSync(stampFile) && (await readFile(stampFile, 'utf8')) === stamp) return;

  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  // three
  const threeOut = join(OUT, 'three');
  await mkdir(threeOut, { recursive: true });
  for (const f of ['three.module.js', 'three.core.js']) await cp(join(NM, 'three', 'build', f), join(threeOut, f));
  const jsmSrc = join(NM, 'three', 'examples', 'jsm');
  const jsmOut = join(threeOut, 'examples', 'jsm');
  await cp(jsmSrc, jsmOut, {
    recursive: true,
    filter: (src) => {
      const rel = src.slice(jsmSrc.length + 1);
      return !THREE_ADDON_EXCLUDE.has(rel.split('/')[0]) && !THREE_ADDON_EXCLUDE_PATHS.some((p) => rel === p || rel.startsWith(p + '/'));
    },
  });
  await cp(join(NM, 'three', 'LICENSE'), join(threeOut, 'LICENSE'));

  // gsap: the ESM sources sit at the package root next to each other.
  const gsapOut = join(OUT, 'gsap');
  await mkdir(gsapOut, { recursive: true });
  for (const f of await readdir(join(NM, 'gsap'))) {
    if (f.endsWith('.js')) await cp(join(NM, 'gsap', f), join(gsapOut, f));
  }

  // motion: bundle the ESM graph (framer-motion/motion-dom/motion-utils) into one file.
  await build({
    root: ROOT,
    configFile: false,
    logLevel: 'warn',
    publicDir: false,
    // Library mode keeps `process.env.NODE_ENV` checks, which throw in a code layer (no `process` in browsers).
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
    build: {
      outDir: join(OUT, 'motion'),
      emptyOutDir: false,
      minify: true,
      target: 'safari17',
      copyPublicDir: false,
      lib: { entry: join(ROOT, 'scripts', 'vendor-motion-entry.mjs'), formats: ['es'], fileName: () => 'motion.js' },
    },
  });
  await cp(join(NM, 'motion', 'LICENSE.md'), join(OUT, 'motion', 'LICENSE.md')).catch(() => {});

  await writeFile(
    join(OUT, 'LICENSES.txt'),
    [
      `three ${versions.three}: MIT (three/LICENSE)`,
      `gsap ${versions.gsap}: GSAP Standard "no charge" license, https://gsap.com/standard-license`,
      `motion ${versions.motion}: MIT`,
      '',
      'Generated by editor/scripts/vendor.mjs from node_modules; do not edit.',
      '',
    ].join('\n'),
  );
  await writeFile(stampFile, stamp);
  console.error(`vendor: three ${versions.three}, gsap ${versions.gsap}, motion ${versions.motion} -> public/vendor`);
}

await main();
