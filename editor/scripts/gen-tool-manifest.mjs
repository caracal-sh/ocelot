#!/usr/bin/env node
// Generates the `ocelot` CLI's tool manifest from the TS tool definitions, so
// `ocelot mcp` answers initialize and tools/list even when the app is closed.
//
//   node scripts/gen-tool-manifest.mjs [--check]
//
// Output: mac/OcelotCLI/Generated/ToolManifest.gen.swift (the document tools + server instructions, a JSON string literal),
// mac/Shared/AppToolManifest.gen.swift and e2e/app-tools.gen.json (the app-scope tools of src/mcp/appTools.ts: the Mac app, the
// CLI and the headless host serve from them).
// `--check` exits 1 when a committed file is stale (run by `bun run test`).

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, '..', 'mac', 'OcelotCLI', 'Generated', 'ToolManifest.gen.swift');
const appOut = join(root, '..', 'mac', 'Shared', 'AppToolManifest.gen.swift');
const appJsonOut = join(root, 'e2e', 'app-tools.gen.json');
const check = process.argv.includes('--check');

const vite = await createServer({ root, logLevel: 'error', appType: 'custom', server: { middlewareMode: true, hmr: false, ws: false }, optimizeDeps: { noDiscovery: true } });
let manifest;
let appManifest;
try {
  const { initializeResult, listTools, SUPPORTED_PROTOCOL_VERSIONS, SERVER_VERSION } = await vite.ssrLoadModule('/src/mcp/protocol.ts');
  manifest = {
    protocolVersions: SUPPORTED_PROTOCOL_VERSIONS,
    initialize: initializeResult(''),
    tools: listTools(false),
  };
  const app = await vite.ssrLoadModule('/src/mcp/appTools.ts');
  appManifest = {
    protocolVersions: SUPPORTED_PROTOCOL_VERSIONS,
    serverInfo: { name: 'ocelot', title: 'Ocelot app', version: SERVER_VERSION },
    instructions: app.APP_INSTRUCTIONS,
    tools: app.listAppTools(false),
    settings: app.APP_SETTINGS,
    securityHint: app.SECURITY_SETTINGS_HINT,
  };
} finally {
  await vite.close();
}

const json = JSON.stringify(manifest);
const appJson = JSON.stringify(appManifest);
if (json.includes('"""') || appJson.includes('"""')) throw new Error('Tool manifest contains a triple quote; adjust the Swift literal in gen-tool-manifest.mjs.');
const swift = `// GENERATED by editor/scripts/gen-tool-manifest.mjs from the TS tool definitions. Do not edit.
// Regenerate with \`bun run gen:manifest\` (in editor/) after changing a tool or the server instructions.

enum ToolManifest {
    /// \`{ protocolVersions, initialize, tools }\`: the \`initialize\` result and the \`tools/list\` array of the app's MCP server.
    static let json = #"""
${json}
"""#
}
`;
const appSwift = `// GENERATED by editor/scripts/gen-tool-manifest.mjs from editor/src/mcp/appTools.ts. Do not edit.
// Regenerate with \`bun run gen:manifest\` (in editor/) after changing an app tool or setting.

enum AppToolManifest {
    /// \`{ instructions, tools, settings, securityHint }\`: the app-scope tools served at /mcp/app (and listed by \`ocelot mcp\`).
    static let json = #"""
${appJson}
"""#
}
`;
const appJsonFile = JSON.stringify(appManifest, null, 2) + '\n';

const files = [
  [out, swift, 'mac/OcelotCLI/Generated/ToolManifest.gen.swift'],
  [appOut, appSwift, 'mac/Shared/AppToolManifest.gen.swift'],
  [appJsonOut, appJsonFile, 'editor/e2e/app-tools.gen.json'],
];
if (check) {
  const stale = files.filter(([file, text]) => !existsSync(file) || readFileSync(file, 'utf8') !== text);
  if (stale.length) {
    console.error(`${stale.map((f) => f[2]).join(', ')} stale. Run: cd editor && bun run gen:manifest`);
    process.exit(1);
  }
  console.log('tool manifests are up to date');
} else {
  for (const [file, text] of files) writeFileSync(file, text);
  console.log(`wrote ${files.map((f) => f[2]).join(', ')} (${manifest.tools.length} document tools, ${appManifest.tools.length} app tools)`);
}
